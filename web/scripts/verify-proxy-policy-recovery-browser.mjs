// 合成层：验证人工恢复的真实UI交互，不代表真实Go/PG活动与退出检查。
async (page) => {
  const base = "http://127.0.0.1:19431";
  const check = (value, message) => { if (!value) throw new Error(message); };
  const evidence = async () => (await page.request.get(`${base}/__fixture/evidence`)).json();
  const control = async (data) => page.request.post(`${base}/__fixture/control`, { data });
  const recoveries = (value) => value.records.filter((record) => record.method === "POST" && record.path === "/api/tasks/12/proxy/policy-recovery");
  page.setDefaultTimeout(8000);
  await page.setViewportSize({ width: 1440, height: 1000 });
  const initial = await evidence();
  let state = initial.policy;
  await control({ behavior: {}, policy: { ...state, proxy_mode: "group", proxy_id: "1", proxy: initial.groups[0].members.find((member) => member.proxy_id === "1").proxy, allowed_group_ids: ["1"], recovery_required: true, latest_switch: null, remaining_switches: 1 } });
  await page.goto(`${base}/function/tasks/detail/?id=12`);
  await page.getByRole("button", { name: "切换任务代理", exact: true }).click();
  let main = page.getByRole("dialog", { name: "任务出口策略", exact: true });
  const openRecovery = async () => {
    await main.getByRole("button", { name: "人工恢复出口策略", exact: true }).click();
    const dialog = page.getByRole("dialog", { name: "人工恢复任务出口策略", exact: true });
    await dialog.getByRole("button", { name: "提交人工策略恢复", exact: true }).waitFor();
    return dialog;
  };
  await main.getByText("当前处于人工恢复屏障", { exact: false }).waitFor();
  check(await main.getByRole("button", { name: "保存出口策略", exact: true }).isDisabled(), "持久屏障未禁止普通PUT");
  check(!(await main.innerText()).includes("203.0.113.1"), "持久屏障仍显示有效旧IP");
  let dialog = await openRecovery();
  const submit = dialog.getByRole("button", { name: "提交人工策略恢复", exact: true });
  await submit.waitFor({ state: "visible" });
  await page.waitForFunction(() => ![...document.querySelectorAll("button")].find((button) => button.textContent === "提交人工策略恢复")?.disabled);
  check(await dialog.getByLabel("恢复操作", { exact: true }).inputValue() === "retry", "默认恢复选择改变出口模式");
  const before = recoveries(await evidence()).length;
  await control({ behavior: { delay: 120 } });
  await submit.evaluate((button) => { button.click(); button.click(); });
  await dialog.getByText("人工恢复已回读确认", { exact: false }).waitFor();
  let value = await evidence();
  check(recoveries(value).length === before + 1, "人工恢复双击重复POST");
  check(JSON.stringify(recoveries(value).at(-1).body) === JSON.stringify({ expected_revision: state.proxy_revision, action: "retry" }), "原恢复发送了模式或退出自证");
  check(value.policy.proxy_mode === "group" && value.policy.remaining_switches === 1, "原恢复切直连或重置预算");
  await page.screenshot({ path: "output/playwright/proxy-groups/policy-recovery-confirmed.png", fullPage: true });
  await dialog.getByRole("button", { name: "关闭恢复", exact: true }).click();
  await main.getByRole("button", { name: "关闭", exact: true }).click();

  // 打开新的明确恢复意图，冲突保留替换策略草稿；采用版本后提交未知结果只GET核对。
  state = (await evidence()).policy;
  await control({ behavior: { writeFailure: 409 }, policy: { ...state, recovery_required: true, latest_switch: null } });
  await page.getByRole("button", { name: "切换任务代理", exact: true }).click();
  main = page.getByRole("dialog", { name: "任务出口策略", exact: true });
  await main.getByText("当前处于人工恢复屏障", { exact: false }).waitFor();
  dialog = await openRecovery();
  await dialog.getByLabel("恢复操作", { exact: true }).selectOption("replace_policy");
  const mode = dialog.getByLabel("连接方式", { exact: true });
  await mode.selectOption("fixed");
  await dialog.getByLabel("指定代理编号", { exact: true }).selectOption("2");
  await dialog.getByRole("button", { name: "提交人工策略恢复", exact: true }).click();
  await dialog.getByText("恢复未确认", { exact: false }).waitFor();
  check(await mode.inputValue() === "fixed", "恢复409丢草稿");
  const conflicted = recoveries(await evidence()).length;
  await dialog.getByRole("button", { name: "仅 GET 核对恢复", exact: true }).click();
  await dialog.getByRole("button", { name: "核对完成并采用恢复版本", exact: true }).waitFor();
  check(recoveries(await evidence()).length === conflicted, "恢复409核对重发POST");
  await page.screenshot({ path: "output/playwright/proxy-groups/policy-recovery-conflict.png", fullPage: true });
  await dialog.getByRole("button", { name: "核对完成并采用恢复版本", exact: true }).click();
  await control({ behavior: { unknownAfterCommit: true } });
  await dialog.getByRole("button", { name: "提交人工策略恢复", exact: true }).click();
  await dialog.getByText("恢复未确认", { exact: false }).waitFor();
  const unknown = recoveries(await evidence()).length;
  await dialog.getByRole("button", { name: "仅 GET 核对恢复", exact: true }).click();
  await dialog.getByText("已 GET 核对当前屏障与版本", { exact: false }).waitFor();
  check(recoveries(await evidence()).length === unknown, "恢复500未知重复POST");
  value = await evidence();
  check(value.policy.proxy_mode === "fixed" && value.policy.proxy_id === "2", "替换恢复未使用明确新策略");
  const receipt = recoveries(value).at(-1).body;
  check(receipt.expected_revision === state.proxy_revision && receipt.action === "replace_policy" && receipt.proxy_id === "2", "替换恢复没有完整CAS策略");
  check(!("exitedConfirmed" in receipt) && !("token" in receipt), "恢复发送退出自证");
  await page.setViewportSize({ width: 390, height: 844 });
  await dialog.evaluate((element) => { element.scrollTop = element.scrollHeight; });
  await page.screenshot({ path: "output/playwright/proxy-groups/policy-recovery-unknown-mobile.png", fullPage: true });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "恢复移动端横向溢出");
  check(await dialog.evaluate((element) => element.scrollWidth <= element.clientWidth && element.getBoundingClientRect().left >= 0 && element.getBoundingClientRect().right <= innerWidth), "恢复弹窗内部内容被横向挤出");
  await dialog.getByRole("button", { name: "关闭恢复", exact: true }).click();
  await main.getByRole("button", { name: "关闭", exact: true }).click();
  await control({ behavior: {} });
  return { synthetic: true, passed: true, recoveryCAS: true, doubleClickOnePOST: true, conflictDraftKept: true, unknownOnlyGET: true, retryPreservesModeAndBudget: true, persistentBarrierHidesIP: true, mobile: true };
}
