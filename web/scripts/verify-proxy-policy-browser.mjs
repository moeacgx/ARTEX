// 合成层：真实浏览器执行共享任务/对话策略，不证明 Go/PG 或实际网络出口。
async (page) => {
  const base = "http://127.0.0.1:19431";
  const check = (value, message) => { if (!value) throw new Error(message); };
  const evidence = async () => (await page.request.get(`${base}/__fixture/evidence`)).json();
  const control = async (data) => page.request.post(`${base}/__fixture/control`, { data });
  const writes = (value) => value.records.filter((record) => record.path === "/api/tasks/12/proxy" && record.method === "PUT");
  page.setDefaultTimeout(8000);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await control({ behavior: {} });
  const trigger = page.getByRole("button", { name: "切换任务代理", exact: true });
  await trigger.click();
  const dialog = page.getByRole("dialog", { name: "任务出口策略" });
  const mode = dialog.getByLabel("连接方式", { exact: true });
  const save = dialog.getByRole("button", { name: "保存出口策略", exact: true });
  check(!await dialog.getByRole("switch", { name: "允许 Agent 在获准组内故障切换" }).isChecked(), "默认给Agent扩权");
  const before = writes(await evidence()).length;
  await mode.selectOption("group");
  await dialog.getByRole("checkbox", { name: /合成获准组/ }).check();
  await dialog.getByRole("switch", { name: "允许 Agent 在获准组内故障切换" }).check();
  await control({ behavior: { delay: 120 } });
  await save.evaluate((button) => { button.click(); button.click(); });
  await dialog.getByText("保存已确认", { exact: false }).waitFor();
  let value = await evidence();
  check(writes(value).length === before + 1, "策略双击重复PUT");
  check(value.policy.proxy_mode === "group" && value.policy.allowed_group_ids.includes("1") && value.policy.agent_failover_enabled, "首次group未原子选成员并保存授权");
  check(value.policy.proxy_id === "1", "group初次未选择组成员");
  await page.screenshot({ path: "output/playwright/proxy-groups/task-group-authorized.png", fullPage: true });
  await mode.selectOption("direct");
  await control({ behavior: { writeFailure: 409 } });
  await save.click();
  await dialog.getByText("版本冲突或主体真实忙碌", { exact: false }).waitFor();
  check(await mode.inputValue() === "direct", "409丢失策略草稿");
  const conflictCount = writes(await evidence()).length;
  await dialog.getByRole("button", { name: "仅刷新核对" }).click();
  await dialog.getByRole("button", { name: "核对完成，保留草稿并采用当前版本" }).waitFor();
  check(writes(await evidence()).length === conflictCount, "409刷新重复PUT");
  await page.screenshot({ path: "output/playwright/proxy-groups/task-conflict.png", fullPage: true });
  await dialog.getByRole("button", { name: "核对完成，保留草稿并采用当前版本" }).click();
  await control({ behavior: { unknownAfterCommit: true } });
  await save.click();
  await dialog.getByText("结果未知，仅允许刷新核对", { exact: false }).waitFor();
  check(await mode.inputValue() === "direct", "未知结果丢失原草稿");
  const unknownCount = writes(await evidence()).length;
  await dialog.getByRole("button", { name: "仅刷新核对" }).click();
  await dialog.getByRole("button", { name: "核对完成，保留草稿并采用当前版本" }).waitFor();
  check(writes(await evidence()).length === unknownCount, "500已提交后再次PUT");
  await page.screenshot({ path: "output/playwright/proxy-groups/task-unknown-get-only.png", fullPage: true });
  await dialog.getByRole("button", { name: "核对完成，保留草稿并采用当前版本" }).click();
  await mode.selectOption("group");
  await control({ behavior: {} });
  await save.click();
  await dialog.getByText("保存已确认", { exact: false }).waitFor();
  await dialog.getByText("根据运行时证据请求故障切换", { exact: true }).click();
  await dialog.getByLabel("故障原因", { exact: true }).fill("合成连接故障");
  await dialog.getByLabel("运行时证据编号", { exact: true }).fill("synthetic-runtime-evidence");
  const options = await dialog.getByLabel("候选出口", { exact: true }).locator("option").allTextContents();
  check(!options.some((text) => text.includes("组外出口") || text.includes("Resin")), "组外或Resin进入切换候选");
  const requestBefore = (await evidence()).records.filter((record) => record.method === "POST" && record.path.endsWith("/switch-requests")).length;
  await dialog.getByRole("button", { name: "请求切换并等待排空" }).evaluate((button) => { button.click(); button.click(); });
  await dialog.getByText("202 不代表切换完成", { exact: false }).waitFor();
  check(await save.isDisabled(), "202处理中仍可写策略");
  value = await evidence();
  check(value.records.filter((record) => record.method === "POST" && record.path.endsWith("/switch-requests")).length === requestBefore + 1, "异步切换双击重复POST");
  check(!(await dialog.innerText()).includes("203.0.113.1"), "pending仍显示旧IP为有效出口");
  await page.screenshot({ path: "output/playwright/proxy-groups/task-pending-202.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "output/playwright/proxy-groups/task-policy-mobile.png", fullPage: true });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "策略移动端溢出");
  await dialog.getByRole("button", { name: "关闭", exact: true }).click();
  await page.goto(`${base}/chat/`);
  await page.getByText("合成对话", { exact: true }).click();
  await page.getByRole("button", { name: "切换对话代理", exact: true }).click();
  const conversation = page.getByRole("dialog", { name: "对话出口策略" });
  await conversation.getByLabel("连接方式", { exact: true }).selectOption("fixed");
  const resin = conversation.getByLabel("指定代理编号", { exact: true }).locator('option[value="4"]');
  check(await resin.isDisabled(), "对话fixed Resin没有禁用");
  check((await resin.innerText()).includes("conversation_resin_lease_scope_unsupported"), "对话Resin未显示具体原因");
  await conversation.getByLabel("连接方式", { exact: true }).selectOption("group");
  await conversation.getByRole("checkbox", { name: /合成获准组/ }).check();
  await conversation.getByRole("button", { name: "保存出口策略" }).click();
  await conversation.getByText("保存已确认", { exact: false }).waitFor();
  value = await evidence();
  check(value.conversationPolicy.proxy_mode === "group" && !value.conversationPolicy.agent_failover_enabled, "对话授权丢失或默认扩权");
  await page.screenshot({ path: "output/playwright/proxy-groups/conversation-policy-mobile.png", fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: "output/playwright/proxy-groups/conversation-policy-desktop.png", fullPage: true });
  return { synthetic: true, passed: true, taskCAS: true, onlyGETAfterUnknown: true, pending202: true, groupScope: true, conversationResinDisabled: true, mobile: true };
}
