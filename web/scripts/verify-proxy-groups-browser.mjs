// 真实 Chromium 加载非 mock 构建；请求由专属 Node fixture 处理，不能作为 Go/PG 验收。
async (page) => {
  const base = "http://127.0.0.1:19431";
  const check = (value, message) => { if (!value) throw new Error(message); };
  const evidence = async () => (await page.request.get(`${base}/__fixture/evidence`)).json();
  const control = async (data) => page.request.post(`${base}/__fixture/control`, { data });
  const count = (data, method, path) => data.records.filter((record) => record.method === method && record.path === path).length;
  const results = [];
  page.setDefaultTimeout(8000);
  await page.setViewportSize({ width: 1440, height: 1000 });
  check(!(await page.locator("body").innerText()).includes("203.0.113.55"), "失败 WARP 显示了旧IP");
  await page.screenshot({ path: "output/playwright/proxy-groups/center-desktop.png", fullPage: true });
  await page.getByRole("button", { name: "新建分组", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByRole("textbox", { name: "分组名称" }).fill("浏览器合成组");
  const before = count(await evidence(), "POST", "/api/proxy-groups");
  await dialog.getByRole("button", { name: "创建分组", exact: true }).evaluate((button) => { button.click(); button.click(); });
  await dialog.getByText("分组已创建。", { exact: false }).waitFor();
  check(count(await evidence(), "POST", "/api/proxy-groups") === before + 1, "创建分组双击重复POST");
  await dialog.getByRole("textbox", { name: "搜索现有代理" }).fill("HTTP 二");
  await dialog.getByRole("checkbox").check();
  await dialog.getByRole("textbox", { name: "搜索现有代理" }).fill("Resin");
  check(await dialog.getByRole("checkbox").isDisabled(), "Resin组成员新选应禁用");
  await dialog.getByRole("button", { name: "保存成员编号" }).click();
  await dialog.getByText("成员已保存并回读确认", { exact: false }).waitFor();
  let value = await evidence();
  const memberCall = value.records.findLast((record) => record.path === "/api/proxy-groups/2/members" && record.method === "PUT");
  check(JSON.stringify(memberCall.body.proxy_ids) === '["2"]' && memberCall.body.expected_revision === 0, "成员未按ID+CAS保存");
  await dialog.getByRole("textbox", { name: "分组名称" }).fill("冲突保留草稿");
  await control({ behavior: { groupConflict: true } });
  await dialog.getByRole("button", { name: "保存名称与启用状态" }).click();
  await dialog.getByText("分组冲突", { exact: false }).waitFor();
  check(await dialog.getByRole("textbox", { name: "分组名称" }).inputValue() === "冲突保留草稿", "组CAS冲突丢草稿");
  const puts = count(await evidence(), "PUT", "/api/proxy-groups/2");
  await dialog.getByRole("button", { name: "仅刷新核对" }).click();
  await dialog.getByRole("button", { name: "核对完成，保留草稿并采用当前版本" }).waitFor();
  check(count(await evidence(), "PUT", "/api/proxy-groups/2") === puts, "刷新重复组PUT");
  await page.screenshot({ path: "output/playwright/proxy-groups/group-conflict-draft.png", fullPage: true });
  await dialog.getByRole("button", { name: "关闭", exact: true }).click();
  await control({ behavior: {} });
  results.push("分组双击/搜索ID/Resin禁选/CAS冲突保留草稿/仅GET核对");
  await page.getByRole("button", { name: "自动恢复设置", exact: true }).click();
  await dialog.getByRole("switch", { name: "允许后台安全自动恢复" }).waitFor();
  check(await dialog.getByRole("switch").isChecked(), "自动恢复没有读取服务端true");
  await dialog.getByRole("switch").uncheck();
  await control({ behavior: { healthUnknown: true } });
  await dialog.getByRole("button", { name: "保存自动恢复设置" }).evaluate((button) => { button.click(); button.click(); });
  await dialog.getByText("保存未确认", { exact: false }).waitFor();
  const healthPuts = count(await evidence(), "PUT", "/api/proxies/5/health-policy");
  check(healthPuts === 1, "健康开关双击重复PUT");
  check(!await dialog.getByRole("switch").isChecked(), "未知结果丢失关闭草稿");
  await dialog.getByRole("button", { name: "仅刷新核对" }).click();
  await dialog.getByText("已核对当前健康策略版本", { exact: false }).waitFor();
  check(count(await evidence(), "PUT", "/api/proxies/5/health-policy") === healthPuts, "未知刷新重发健康PUT");
  await page.screenshot({ path: "output/playwright/proxy-groups/warp-policy-unknown.png", fullPage: true });
  await dialog.getByRole("button", { name: "关闭", exact: true }).click();
  await page.getByRole("button", { name: "人工核对与恢复", exact: true }).click();
  await dialog.getByRole("button", { name: "提交人工恢复意图" }).evaluate((button) => { button.click(); button.click(); });
  await dialog.getByText("恢复状态待核对", { exact: false }).waitFor();
  await dialog.getByRole("button", { name: "仅回读原出口状态" }).click();
  await dialog.getByText("已回读原出口运行状态", { exact: false }).waitFor();
  value = await evidence();
  const recovery = value.records.filter((record) => record.path === "/api/proxies/5/health/recovery");
  check(recovery.length === 1 && JSON.stringify(recovery[0].body) === "{}", "恢复重复POST或发送自证字段");
  await page.screenshot({ path: "output/playwright/proxy-groups/warp-recovery-barrier.png", fullPage: true });
  await dialog.getByRole("button", { name: "取消", exact: true }).click();
  results.push("WARP未知只GET/关闭草稿保留/恢复空对象/双击仅一次/失败IP隐藏");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "output/playwright/proxy-groups/center-mobile.png", fullPage: true });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), "移动端横向溢出");
  return { synthetic: true, passed: true, layer: "Chromium → 非mock UI → Node合成HTTP", results };
}
